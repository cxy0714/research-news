"""AI auto-research agents radar — the second daily arXiv track.

Topic: **AI agents that do research itself** ("AI auto-research agent") —
end-to-end research pipelines (AI Scientist / Agent Laboratory), idea and
hypothesis generation, experiment automation and self-driving labs,
literature-review agents, and the evaluation of such systems.

Same shape as the AI-evaluation radar (``research_news.benchmarks daily``), so
the two tracks share the wrapper, the daily mutex and the render style:

    fetch today's arXiv -> keyword prefilter (zero LLM) -> LLM score ->
    annotate the top N -> render one page per day under docs/autoresearch/daily/

Entry points::

    python -m research_news.autoresearch daily                 # today
    python -m research_news.autoresearch daily --date 2026-11-11
    python -m research_news.autoresearch daily --if-missing    # idempotent
    python -m research_news.autoresearch daily --dry-run       # prefilter only
    python -m research_news.autoresearch render                # index + nav only

The ``--if-missing`` flag exists because the page can be produced by either the
daily wrapper (run_daily.ps1, fallback) or the dedicated scheduled task
(run_ai_radar.ps1 -Radar autoresearch, primary); whichever runs first wins and
the other one no longer spends LLM calls on a page that already exists.
"""
from __future__ import annotations

import argparse
import logging
import re
from datetime import date
from pathlib import Path

import yaml

from .llm.autoresearch_prompts import (
    AR_SCORE_SYSTEM,
    AR_SUMMARY_SYSTEM,
    AR_TOPIC_LABELS_ZH,
    AR_TOPICS,
)
from .llm.pipeline import score_papers, summarize_paper
from .llm.sjtu_client import SJTUClient
from .models import Paper
from .scrapers.arxiv import fetch_all as fetch_arxiv
from .usage import report as usage_report

log = logging.getLogger("research_news.autoresearch")

CONFIG_PATH = Path("config/autoresearch.yaml")
INTERESTS_PATH = Path("config/interests.autoresearch.yaml")
DOCS_ROOT = Path("docs/autoresearch")
DAILY_DIR = DOCS_ROOT / "daily"
MKDOCS = Path("mkdocs.yml")
NAV_START = (
    "# AUTORESEARCH-NAV-START (auto-generated by "
    "`python -m research_news.autoresearch render` — do not edit between markers)"
)
NAV_END = "# AUTORESEARCH-NAV-END"


# ── config ───────────────────────────────────────────────────────────────────

def load_config() -> dict:
    return yaml.safe_load(CONFIG_PATH.read_text(encoding="utf-8")) or {}


def load_interests() -> tuple[str, dict]:
    text = INTERESTS_PATH.read_text(encoding="utf-8")
    return text, (yaml.safe_load(text) or {})


def _compile(patterns: list[str]) -> list[re.Pattern]:
    return [re.compile(p, re.I) for p in patterns]


def _matches(title: str, abstract: str, filt: dict) -> bool:
    """Deny on title, then match title, then fall back to high-precision abstract
    phrases.

    Unlike the benchmark track (title-only), auto-research papers frequently
    announce themselves only in the abstract ("we build a multi-agent research
    pipeline"), so a short high-precision phrase list is applied to the abstract.
    """
    if any(r.search(title) for r in _compile(filt.get("deny_title_patterns", []))):
        return False
    if any(r.search(title) for r in _compile(filt.get("title_patterns", []))):
        return True
    return any(r.search(abstract or "") for r in _compile(filt.get("abstract_patterns", [])))


def _write(path: Path, lines: list[str]) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    return path


# ── rendering helpers ────────────────────────────────────────────────────────

def _link(p: Paper) -> str:
    bits: list[str] = []
    if p.proceedings_url or p.url:
        bits.append(f"[论文页]({p.proceedings_url or p.url})")
    if p.pdf_url:
        bits.append(f"[PDF]({p.pdf_url})")
    if p.arxiv_id:
        bits.append(f"[arXiv](https://arxiv.org/abs/{p.arxiv_id})")
    return " · ".join(bits)


def card(p: Paper, n: int) -> list[str]:
    out = [f"### {n}. {p.title}"]
    if link := _link(p):
        out.append(f"- **链接**: {link}")
    authors = ", ".join(p.authors[:8]) + (" et al." if len(p.authors) > 8 else "")
    if authors:
        out.append(f"- **作者**: {authors}")
    source = "arXiv" + (f" · {p.venue_track}" if p.venue_track else "")
    out.append(f"- **来源**: {source}")
    meta: list[str] = []
    if p.score is not None:
        meta.append(f"相关性 {p.score:.0f}/10")
    if p.bench_type:
        meta.append(f"自动化程度 `{p.bench_type}`")
    if meta:
        out.append("- " + " · ".join(meta))
    if p.what_it_measures:
        out.append(f"- **自动化的环节**: {p.what_it_measures}")
    if p.summary_zh:
        out.append(f"- **摘要**: {p.summary_zh}")
    if p.why_relevant:
        out.append(f"- **为什么值得看**: {p.why_relevant}")
    if p.key_techniques:
        out.append("- **关键技术**: " + ", ".join(f"`{k}`" for k in p.key_techniques))
    return out


def _groups(papers: list[Paper]) -> dict[str, list[Paper]]:
    groups: dict[str, list[Paper]] = {}
    for p in papers:
        t = p.topic if p.topic in AR_TOPICS else "other"
        groups.setdefault(t, []).append(p)
    for items in groups.values():
        items.sort(key=lambda x: x.score or 0, reverse=True)
    return groups


def _write_daily_index() -> Path:
    DAILY_DIR.mkdir(parents=True, exist_ok=True)
    idx = [
        "# AI Auto-Research 每日雷达",
        "",
        "> 每天从 arXiv `cs.CL` / `cs.LG` / `cs.AI` / `cs.MA` 的提交里筛",
        "> 「AI 自动科研 / research agent」：端到端科研流水线、假设生成、实验自动化、",
        "> 文献调研 agent，以及这类系统的评测。按自动化程度与证据质量打分并精摘。",
        "",
    ]
    pages = [f for f in sorted(DAILY_DIR.glob("*.md"), reverse=True) if f.name != "index.md"]
    if pages:
        for f in pages:
            idx.append(f"- [{f.stem}]({f.name})")
    else:
        idx.append("*（还没有每日页面）*")
    return _write(DAILY_DIR / "index.md", idx)


def render_nav() -> None:
    """Refresh the nav block in mkdocs.yml between the AUTORESEARCH markers.

    A no-op when the markers are missing, so a hand-edited nav never gets
    clobbered — same contract as the benchmark track's nav block.
    """
    if not MKDOCS.exists():
        return
    text = MKDOCS.read_text(encoding="utf-8")
    if NAV_START not in text or NAV_END not in text:
        log.warning("nav markers missing in mkdocs.yml; skipping nav update")
        return
    block = [NAV_START, "  - AI 自动科研:", "    - 每日雷达: autoresearch/daily/index.md"]
    block.append(NAV_END)
    new = re.sub(
        re.escape(NAV_START) + r".*?" + re.escape(NAV_END),
        "\n".join(block),
        text,
        flags=re.S,
    )
    if new != text:
        MKDOCS.write_text(new, encoding="utf-8")
        log.info("updated AI-auto-research nav in mkdocs.yml")


# ── the daily radar ──────────────────────────────────────────────────────────

def daily(
    for_date: date | None = None,
    *,
    model: str | None = None,
    dry_run: bool = False,
    skip_existing: bool = False,
) -> Path | None:
    cfg = load_config()
    dcfg = cfg.get("daily", {})
    when = for_date or date.today()

    out_path = DAILY_DIR / f"{when.isoformat()}.md"
    if skip_existing and out_path.exists():
        log.info("[autoresearch %s] page already exists (%s) — skipping", when, out_path)
        return out_path

    arxiv_cfg = {
        "categories": dcfg.get("categories", ["cs.CL", "cs.LG", "cs.AI", "cs.MA"]),
        "include_cross_listed": bool(dcfg.get("include_cross_listed", False)),
        "max_per_category": int(dcfg.get("max_per_category", 400)),
    }
    papers = fetch_arxiv(arxiv_cfg, for_date=when if when != date.today() else None)
    log.info("[autoresearch %s] fetched %d arXiv papers", when, len(papers))

    filt = cfg.get("filter", {})
    seen: set[str] = set()
    uniq: list[Paper] = []
    for p in papers:
        if not _matches(p.title, p.abstract, filt):
            continue
        if p.paper_id in seen:
            continue
        seen.add(p.paper_id)
        p.venue = "arXiv"
        p.venue_track = p.categories[0] if p.categories else ""
        p.track = "ai-auto-research"
        p.arxiv_id = p.paper_id
        p.proceedings_url = p.url
        p.pdf_url = f"https://arxiv.org/pdf/{p.paper_id}"
        uniq.append(p)
    uniq = uniq[: int(dcfg.get("max_candidates", 120))]
    log.info("[autoresearch %s] %d candidates after prefilter", when, len(uniq))

    if dry_run:
        for p in uniq[:20]:
            print(f"  {p.paper_id}  {p.title[:100]}")
        return None

    if not uniq:
        log.info("[autoresearch %s] no candidates; nothing to render", when)
        _write_daily_index()
        render_nav()
        return None

    interests_text, icfg = load_interests()
    client = SJTUClient()
    scores = score_papers(
        client, uniq, interests_text, model=model, system_prompt=AR_SCORE_SYSTEM
    )
    for p in uniq:
        if p.paper_id in scores:
            p.score, p.score_reason = scores[p.paper_id]
    scored = [p for p in uniq if p.score is not None]
    scored.sort(key=lambda p: p.score or 0, reverse=True)

    th_show = float(icfg.get("score_threshold_show", 4))
    show = int(dcfg.get("max_shown", 12))
    to_sum = [p for p in scored if (p.score or 0) >= th_show][: int(dcfg.get("max_summarized", 10))]
    for p in to_sum:
        try:
            summarize_paper(
                client, p, interests_text, model=model,
                system_prompt=AR_SUMMARY_SYSTEM, topics=AR_TOPICS,
            )
        except Exception as e:  # noqa: BLE001
            log.warning("[autoresearch %s] summary failed for %s: %s", when, p.paper_id, e)

    lines = [
        f"# {when.isoformat()} · AI Auto-Research 雷达",
        "",
        f"- 候选 **{len(uniq)}** 篇（arXiv {', '.join(arxiv_cfg['categories'])}）· "
        f"打分 **{len(scored)}** · 精摘 **{len(to_sum)}**",
        "- 口径：自动化了哪几环科研流程、人还负责什么、证据是否支撑「自主」的说法。",
        "",
    ]
    groups = _groups([p for p in scored if p.summary_zh])
    for topic in AR_TOPICS:
        items = groups.get(topic, [])
        if not items:
            continue
        lines.append(f"## {AR_TOPIC_LABELS_ZH.get(topic, topic)}")
        lines.append("")
        for i, p in enumerate(items[:show], 1):
            lines.extend(card(p, i))
            lines.append("")
    if len(scored) > len(to_sum):
        lines += ["## 其他候选", "", "| 论文 | 来源 | 分数 | 链接 |", "|---|---|---:|---|"]
        for p in scored[len(to_sum):][:30]:
            title = p.title.replace("|", "\\|")
            links = []
            if p.url:
                links.append(f"[页]({p.url})")
            if p.pdf_url:
                links.append(f"[PDF]({p.pdf_url})")
            lines.append(
                f"| {title} | {p.venue_track or '-'} | {p.score:.0f} | "
                f"{' · '.join(links) or '-'} |"
            )
        lines.append("")

    out = _write(out_path, lines)
    _write_daily_index()
    render_nav()
    usage_report(client, "autoresearch-daily")
    log.info("[autoresearch %s] rendered %s", when, out)
    return out


# ── CLI ──────────────────────────────────────────────────────────────────────

def _setup_logging() -> None:
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s %(levelname)s %(name)s: %(message)s",
        datefmt="%H:%M:%S",
    )


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m research_news.autoresearch")
    sub = ap.add_subparsers(dest="cmd", required=True)

    p_daily = sub.add_parser("daily", help="daily arXiv auto-research radar")
    p_daily.add_argument("--date", default=None)
    p_daily.add_argument("--model", default=None)
    p_daily.add_argument("--dry-run", action="store_true")
    p_daily.add_argument("--if-missing", action="store_true",
                         help="skip when that day's page already exists")

    sub.add_parser("render", help="rebuild the daily index and the nav block")

    args = ap.parse_args(argv)
    _setup_logging()

    if args.cmd == "daily":
        when = date.fromisoformat(args.date) if args.date else None
        daily(when, model=args.model, dry_run=args.dry_run, skip_existing=args.if_missing)
    elif args.cmd == "render":
        _write_daily_index()
        render_nav()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
