def download_pdf(arxiv_id: str) -> Path | None:
    """Download an arXiv PDF into the conference cache (reused if present)."""
    if not arxiv_id:
        return None
    PDF_DIR.mkdir(parents=True, exist_ok=True)
    dest = PDF_DIR / f"{_slug(arxiv_id)}.pdf"
    if dest.exists() and dest.stat().st_size > 1024:
        return dest
    import httpx

    url = f"https://arxiv.org/pdf/{arxiv_id}"
    try:
        with httpx.Client(timeout=90, follow_redirects=True,
                          headers={"User-Agent": "research-news/1.0"}) as c:
            r = c.get(url)
            r.raise_for_status()
            if not r.content.startswith(b"%PDF-"):
                log.warning("PDF for %s is not a PDF (%d bytes)", arxiv_id, len(r.content))
                return None
            dest.write_bytes(r.content)
            return dest
    except Exception as e:  # noqa: BLE001
        log.warning("PDF download failed for %s: %s", arxiv_id, e)
        return None


def _paper_text(arxiv_id: str) -> str:
    if not arxiv_id:
        return ""
    dest = download_pdf(arxiv_id)
    if not dest:
        return ""
    from .deep_read import extract_pdf_text

    return extract_pdf_text(dest, max_chars=MAX_PDF_CHARS)


