QUEUE_HEADER = """# XAGI 2026 精读队列（Runbook · agent 用）

XAGI 2026 交叉智能大会（2026.10.16-18，北京友谊宾馆）的**逐场精读**队列。
**一格 = 一场报告**，从第一个未打勾的格子开始，顺序执行、绝不并行。

- 驱动：`python -m research_news.xagi backfill --max 1`（Windows 计划任务走 `run_xagi_backfill.ps1`）。
- **共享锁**：与 daily、期刊回补共用 `Global\\research-news-daily` 互斥量，同一时刻只允许一个任务。
- **可续跑**：每格把结果写到 `data/conferences/xagi2026/research/<cell>.json`；已生成的格子
  重跑会跳过（`--force` 才重做），所以中断 / 重跑都安全。
- **产物**：`docs/conferences/xagi2026/session-XX.md`（逐场精读页，随进度刷新）、
  `docs/deep_reads/xagi2026-<arXiv>.md`（对应论文的长篇精读）。
- 打勾由驱动自动完成（`- [ ]` → `- [x] (日期)`）；要重做某格，就把它改回 `- [ ]` 再跑。

## Queue
"""


def render_queue(data: dict | None = None, path: Path = QUEUE_PATH) -> str:
    """Rewrite the queue, preserving each cell's checked state (git = state)."""
    data = data or load_sessions()
    done: dict[str, bool] = {}
    if path.exists():
        for line in path.read_text(encoding="utf-8").splitlines():
            m = re.match(r"^\s*-\s*\[([ xX])\]\s*`([^`]+)`", line)
            if m:
                done[m.group(2)] = m.group(1).lower() == "x"

    lines = [QUEUE_HEADER]
    for session in data.get("sessions") or []:
        label = (f"### Session {session['no']:02d} · {session['title']} · "
                 f"{session.get('date') or ''} {session.get('time') or ''} · "
                 f"{session.get('room') or ''}").rstrip(" ·")
        lines.append(label)
        for talk in session.get("talks") or []:
            cell = talk["id"]
            box = "x" if done.get(cell) else " "
            stamp = ""
            if done.get(cell):
                rec = _load_research(cell) or {}
                at = (rec.get("generated_at") or "")[:10]
                stamp = f" ({at})" if at else ""
            lines.append(
                f"- [{box}]{stamp} `{cell}` {talk.get('title') or '(无题目)'} — "
                f"{talk.get('speaker') or '?'}（{talk.get('org') or '?'}）"
            )
        lines.append("")
    body = "\n".join(lines).rstrip() + "\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body, encoding="utf-8")
    return body


def pending_cells(path: Path = QUEUE_PATH) -> list[tuple[int, str]]:
    """(line index, cell id) for every unchecked queue line, in order."""
    if not path.exists():
        return []
    out: list[tuple[int, str]] = []
    for i, line in enumerate(path.read_text(encoding="utf-8").splitlines()):
        m = _QUEUE_ITEM_RE.match(line)
        if m:
            out.append((i, m.group(3).strip()))
    return out


def mark_done(line: str, when: date) -> str:
    m = _QUEUE_ITEM_RE.match(line)
    if not m:
        return line
    prefix, gap, cell, tail = m.groups()
    return f"{prefix}[x] ({when.isoformat()}){gap}`{cell}`{tail}"


# ── backfill driver ──────────────────────────────────────────────────────────

def backfill(*, max_units: int = 1, dry_run: bool = False,
             queue_path: Path = QUEUE_PATH, force: bool = False) -> int:
    """Do up to ``max_units`` queue cells, one subprocess each. Returns #done.

    A failing cell is logged, left unchecked, and skipped (so one bad talk can't
    stall the whole conference); the run exits non-zero only when nothing at all
    could be done.
    """
    pending = pending_cells(queue_path)
    if not pending:
        log.info("XAGI queue is empty — every talk is read")
        return 0
    log.info("%d cell(s) left in the queue; doing up to %d", len(pending), max_units)
    done = 0
    for idx, cell in pending:
        if done >= max_units:
            break
        if dry_run:
            log.info("would read %s", cell)
            done += 1
            continue
        argv = [sys.executable, "-m", "research_news.xagi", "read", "--cell", cell]
        if force:
            argv.append("--force")
        log.info("next cell: %s", cell)
        proc = subprocess.run(argv)
        if proc.returncode != 0:
            log.error("cell %s exited %d — leaving unchecked", cell, proc.returncode)
            continue
        lines = queue_path.read_text(encoding="utf-8").splitlines()
        if idx < len(lines):
            lines[idx] = mark_done(lines[idx], date.today())
            queue_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        done += 1
    if not dry_run:
        try:
            render()
        except Exception as e:  # noqa: BLE001
            log.warning("render after backfill failed: %s", e)
    log.info("%s %d cell(s)", "would do" if dry_run else "did", done)
    return done


