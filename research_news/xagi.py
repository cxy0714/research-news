def _session_label(session: dict) -> str:
    parts = [f"Session {session['no']:02d}", session.get("title") or ""]
    return " · ".join(p for p in parts if p)


def _date_cn(iso: str | None) -> str:
    try:
        d = date.fromisoformat(iso or "")
    except ValueError:
        return iso or ""
    return f"{d.month} 月 {d.day} 日"


def _talk_status(session: dict, talk: dict) -> tuple[bool, bool]:
    """(has_short_read, has_long_read)."""
    rec = _load_research(talk["id"]) or {}
    return bool(rec.get("short_read")), bool(rec.get("long_read"))


def _paper_line(talk: dict, rec: dict | None) -> list[str]:
    paper = (rec or {}).get("paper") or talk.get("paper")
    if paper is None:
        return ["**对应论文**：待匹配（精读该场时自动检索 arXiv / OpenAlex）", ""]
    if not paper.get("found"):
        return ["**对应论文**：未检索到公开论文（以下为依据报告摘要与讲者方向的推断）", ""]
    title = paper.get("title") or talk.get("title")
    links = []
    if paper.get("arxiv_id"):
        links.append(f"[arXiv:{paper['arxiv_id']}](https://arxiv.org/abs/{paper['arxiv_id']})")
    elif paper.get("doi"):
        links.append(f"[DOI](https://doi.org/{paper['doi']})")
    elif paper.get("url"):
        links.append(f"[论文页]({paper['url']})")
    if rec and rec.get("long_read"):
        links.append(f"📖 [长篇精读](../../{rec['long_read']})")
    line = f"**对应论文**：{title}"
    if links:
        line += " · " + " · ".join(links)
    return [line, ""]


