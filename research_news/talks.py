def _slug(s: str) -> str:
    return re.sub(r"[^A-Za-z0-9_.-]+", "_", s).strip("_") or "unknown"


# ── config ────────────────────────────────────────────────────────────────────

def _talk_from_raw(raw: dict) -> Talk | None:
    if not raw.get("id") or not raw.get("url"):
        log.warning("skipping talk with missing id/url: %r", raw)
        return None
    topic = (raw.get("topic") or "").strip().lower() or None
    if topic and topic not in TOPICS:
        log.warning("talk %s: unknown topic %r → 'other'", raw["id"], topic)
        topic = "other"
    return Talk(
        id=str(raw["id"]),
        url=str(raw["url"]),
        title=raw.get("title"),
        speaker=raw.get("speaker"),
        venue=raw.get("venue"),
        date=str(raw["date"]) if raw.get("date") is not None else None,
        papers=[str(p) for p in (raw.get("papers") or [])],
        topic=topic,
        asr_prompt=raw.get("asr_prompt"),
        language=raw.get("language"),
        segments=list(raw.get("segments") or []),
        abstract=raw.get("abstract"),
        discussant=raw.get("discussant"),
        slides=raw.get("slides"),
    )


def load_talks(path: Path | None = None) -> tuple[str, list[Talk]]:
    """Return (asr_prompt_default, [Talk, ...]).

    Reads the hand-curated config/talks.yaml plus, if present, the auto-generated
    config/talks.ocis.yaml (from `talks import-ocis`). On an id collision the
    hand-curated file wins. asr_prompt_default comes from the hand-curated file.
    """
    path = path or TALKS_CONFIG
    default_prompt = ""
    talks: list[Talk] = []
    seen: set[str] = set()

    for cfg_path, is_primary in ((path, True), (OCIS_TALKS_CONFIG, False)):
        if not cfg_path.exists():
            if is_primary:
                log.warning("no talks config at %s", cfg_path)
            continue
        cfg = yaml.safe_load(cfg_path.read_text(encoding="utf-8")) or {}
        if is_primary:
            default_prompt = (cfg.get("asr_prompt_default") or "").strip()
        for raw in cfg.get("talks", []) or []:
            t = _talk_from_raw(raw)
            if t is None or t.id in seen:
                continue
            seen.add(t.id)
            talks.append(t)
    return default_prompt, talks


def transcript_path(talk_id: str) -> Path:
    return TRANSCRIPTS_DIR / f"{_slug(talk_id)}.txt"


def _asr_prompt(talk: Talk, default: str) -> str | None:
    parts = [p.strip() for p in (default, talk.asr_prompt) if p and p.strip()]
    return ", ".join(parts) or None


# ── dates ─────────────────────────────────────────────────────────────────────

def talk_date(talk: Talk) -> date:
    """Best-effort calendar date for filename / sorting. YYYY-MM-DD or YYYY-MM
    (→ first of month); anything else falls back to today."""
    s = (talk.date or "").strip()
    m = re.match(r"^(\d{4})-(\d{2})(?:-(\d{2}))?", s)
    if m:
        y, mo, d = int(m.group(1)), int(m.group(2)), int(m.group(3) or 1)
        try:
            return date(y, mo, d)
        except ValueError:
            pass
    return date.today()


# ── ingest (local: download + ASR) ────────────────────────────────────────────

def ingest(
    talk: Talk,
    asr_default: str = "",
    *,
    model_size: str = "large-v3",
    prefer_subs: bool = False,
    subs_file: str | None = None,
    force: bool = False,
) -> Path | None:
    """Produce data/talks/<id>.txt for one talk. Returns the path (or None on
    failure).

    Source of the transcript, in priority order:
      - ``subs_file``: an existing .srt/.vtt you made with any tool (whisper.cpp,
        etc.) — no download, no ASR, fully offline;
      - ``prefer_subs``: the video's own (auto)captions, if present — no ASR;
      - otherwise: download audio + faster-whisper ASR (needs the [asr] extra +
        ffmpeg). On a 4 GB GPU pass model_size="distil-large-v3" or "small".
    """
    dest = transcript_path(talk.id)
    if dest.exists() and not force:
        log.info("transcript already present: %s (use --force to redo)", dest)
        return dest

    segments: list[dict] | None = None
    if subs_file:
        vtt = Path(subs_file).read_text(encoding="utf-8", errors="ignore")
        segments = tr.parse_vtt(vtt)
        log.info("using subtitle file %s for %s (%d cues)", subs_file, talk.id, len(segments))
    elif prefer_subs:
        # Subtitles ONLY — never silently fall back to ASR in a bulk run. If the
        # video has no captions (or YouTube rate-limits us with a 429), skip and
        # move on; a later `ingest` without --prefer-subs ASRs the leftovers.
        try:
            vtt = tr.fetch_subtitles(talk.url, AUDIO_DIR, talk.id, lang=talk.language or "en")
        except Exception as e:  # noqa: BLE001
            log.warning("subtitle fetch failed for %s: %s — skipping", talk.id, e)
            return None
        segments = tr.parse_vtt(vtt) if vtt else None
        if not segments:
            log.info("no captions for %s — skipping (run `ingest` without --prefer-subs to ASR it)",
                     talk.id)
            return None
        log.info("using existing subtitles for %s (%d cues)", talk.id, len(segments))

    if segments is None:
        log.info("downloading audio for %s ...", talk.id)
        audio = tr.download_audio(talk.url, AUDIO_DIR, talk.id)
        log.info("transcribing %s (this can take a while) ...", audio.name)
        segments = tr.transcribe_audio(
            audio,
            model_size=model_size,
            initial_prompt=_asr_prompt(talk, asr_default),
            language=talk.language,
        )

    text = tr.clean_transcript(tr.segments_to_text(segments))
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(text + "\n", encoding="utf-8")
    log.info("wrote transcript %s (%d chars)", dest, len(text))
    return dest


# ── cross-linking to paper deep-reads ─────────────────────────────────────────

def _is_arxiv_id(pid: str) -> bool:
    return bool(_ARXIV_ID_RE.match(pid.strip()))


def _paper_url(pid: str) -> str:
    pid = pid.strip()
    if _is_arxiv_id(pid):
        return f"https://arxiv.org/abs/{pid}"
    if pid.lower().startswith("10."):
        return f"https://doi.org/{pid}"
    return pid


def _load_deep_reads_index() -> list[dict]:
    if not DEEP_READS_INDEX.exists():
        return []
    try:
        data = json.loads(DEEP_READS_INDEX.read_text(encoding="utf-8"))
        return data if isinstance(data, list) else []
    except Exception:
        return []


def resolve_paper_links(talk: Talk) -> list[dict]:
    """Map each of the talk's `papers` ids to {id, title, doc_path|None, url}.

    doc_path is the deep-read page (relative to docs/) when one exists, else None.
    """
    by_id = {e.get("paper_id"): e for e in _load_deep_reads_index()}
    out: list[dict] = []
    for pid in talk.papers or []:
        e = by_id.get(pid)
        out.append({
            "id": pid,
            "title": e.get("title") if e else None,
            "doc_path": e.get("doc_path") if e else None,
            "url": _paper_url(pid),
        })
    return out


def _paper_links_md(links: list[dict]) -> list[str]:
    """Render the '## 相关论文' section for a talk page (talk pages live in
    docs/talks/, so deep-read links are '../deep_reads/...')."""
    if not links:
        return []
    lines = ["## 相关论文\n"]
    for lk in links:
        if lk["doc_path"]:
            title = lk["title"] or lk["id"]
            lines.append(f"- [{title}](../{lk['doc_path']}) · [原文]({lk['url']})")
        else:
            lines.append(
                f"- [{lk['id']}]({lk['url']}) "
                f"*（尚未精读 — `talks read --id … --read-papers` 可补）*"
            )
    lines.append("")
    return lines


def read_linked_papers(
    client: "SJTUClient",
    talk: Talk,
    interests_text: str,
    *,
    model: str | None = None,
    run_date: date | None = None,
) -> int:
    """Deep-read any of the talk's arXiv papers not already in the index, so the
    cross-links resolve. Best-effort; returns how many were newly read."""
    from .deep_read import generate_deep_read_report, load_index
    from .highlights import save_highlights
    from .llm.pipeline import summarize_paper

    have = {e.get("paper_id") for e in load_index()}
    fresh: list[Paper] = []
    for pid in talk.papers or []:
        if pid in have:
            continue
        if not _is_arxiv_id(pid):
            log.info("talk %s: %s is not an arXiv id — link only, not auto-read", talk.id, pid)
            continue
        paper = fetch_arxiv_by_id(pid)
        if not paper:
            continue
        try:
            summarize_paper(client, paper, interests_text, model=model)
        except Exception as e:  # noqa: BLE001
            log.warning("first-pass summary failed for %s: %s", pid, e)
        fresh.append(paper)

    if not fresh:
        return 0
    run_date = run_date or date.today()
    save_highlights(fresh, run_date=run_date)
    generate_deep_read_report(fresh, client, interests_text, run_date, "talk", model=model)
    log.info("auto-read %d linked paper(s) for talk %s", len(fresh), talk.id)
    return len(fresh)


def fetch_arxiv_by_id(arxiv_id: str) -> "Paper | None":
    """Fetch a single arXiv paper's metadata by id (for --read-papers)."""
    import httpx
    from xml.etree import ElementTree as ET

    from .scrapers.arxiv import ATOM, _api_entry_to_paper, _headers

    try:
        with httpx.Client(timeout=40, headers=_headers(), follow_redirects=True) as c:
            r = c.get("https://export.arxiv.org/api/query",
                      params={"id_list": arxiv_id, "max_results": 1})
            r.raise_for_status()
        entry = ET.fromstring(r.text).find(f"{ATOM}entry")
        if entry is None:
            log.warning("arXiv returned no entry for %s", arxiv_id)
            return None
        res = _api_entry_to_paper(entry)
        return res[0] if res else None
    except Exception as e:  # noqa: BLE001
        log.warning("arXiv fetch by id %s failed: %s", arxiv_id, e)
        return None


# ── LLM read ──────────────────────────────────────────────────────────────────

def build_user_message(
    talk: Talk,
    transcript: str,
    interests_text: str,
    *,
    context: str = "",
    segment_title: str | None = None,
    segment_speaker: str | None = None,
) -> str:
    meta = [
        f"Title: {segment_title or talk.title or talk.id}",
        f"Speaker: {segment_speaker or talk.speaker or 'unknown'}",
        f"Venue: {talk.venue or 'unknown'}",
        f"Date: {talk.date or 'unknown'}",
        f"Video: {talk.url}",
    ]
    if talk.discussant:
        meta.append(f"Discussant: {talk.discussant}")
    if talk.papers:
        meta.append("Candidate papers (verify against the talk): " + ", ".join(talk.papers))
    transcript = transcript[:MAX_TRANSCRIPT_CHARS]
    return (
        "## Researcher interests\n" + interests_text + "\n\n"
        "## Talk metadata\n" + "\n".join(meta) + "\n\n"
        + (context + "\n\n" if context else "")
        + "## Transcript (ASR — may contain errors; timestamps are [H:MM:SS])\n"
        + transcript + "\n"
    )


_DRIVE_ID_RE = re.compile(r"/file/d/([^/]+)|[?&]id=([^&]+)")


def _drive_id(url: str) -> str | None:
    m = _DRIVE_ID_RE.search(url or "")
    return (m.group(1) or m.group(2)) if m else None


def _drive_pdf_url(url: str) -> str:
    """Turn a Google Drive 'file/d/<id>/view' (or '?id=') link into a direct
    download URL; pass other URLs through (a direct .pdf works as-is)."""
    fid = _drive_id(url)
    return f"https://drive.google.com/uc?export=download&id={fid}" if fid else url


_PRESENTATION_RE = re.compile(r"docs\.google\.com/presentation/d/([^/?#]+)")


def _slides_candidates(url: str) -> list[str]:
    """Ordered list of direct-download URLs to try for a slides link, by host:
    Google Drive file, Google Slides presentation (→ export/pdf), Dropbox
    (→ dl=1), or a plain PDF URL as-is."""
    fid = _drive_id(url)
    if fid:
        # confirm=t bypasses the Drive virus-scan interstitial; uc?... is fallback
        return [f"https://drive.usercontent.google.com/download?id={fid}&export=download&confirm=t",
                f"https://drive.google.com/uc?export=download&id={fid}"]
    m = _PRESENTATION_RE.search(url)
    if m:
        return [f"https://docs.google.com/presentation/d/{m.group(1)}/export/pdf"]
    if "dropbox.com" in url:
        u = re.sub(r"[?&]dl=0", "", url)
        return [u + ("&" if "?" in u else "?") + "dl=1"]
    return [url]


def download_slides(talk: Talk, *, force: bool = False) -> Path | None:
    """Download the talk's slide deck to data/talks/slides/<id>.pdf (best-effort).
    Returns the path, or None (no slides URL, private / stale link, non-PDF,
    network error). Reuses a cached file unless `force`. Handles Google Drive +
    Google Slides + Dropbox + plain PDF URLs."""
    if not talk.slides:
        return None
    dest = slides_path(talk.id)
    if dest.exists() and not force:
        return dest
    import httpx
    SLIDES_DIR.mkdir(parents=True, exist_ok=True)
    headers = {"User-Agent": "Mozilla/5.0 (research-news)", "Accept": "application/pdf,*/*"}
    try:
        with httpx.Client(timeout=90, follow_redirects=True, headers=headers) as c:
            for url in _slides_candidates(talk.slides):
                try:
                    r = c.get(url)
                except Exception:  # noqa: BLE001 - try the next candidate
                    continue
                if r.status_code == 200 and r.content.startswith(b"%PDF-"):
                    dest.write_bytes(r.content)
                    return dest
    except Exception as e:  # noqa: BLE001
        log.info("slides download failed for %s: %s", talk.id, e)
        return None
    log.info("slides for %s: no downloadable PDF (private / stale / unsupported host)", talk.id)
    return None


def fetch_slides_text(talk: Talk, *, max_chars: int = MAX_SLIDES_CHARS) -> str:
    """Download (if needed) the talk's slide deck and extract its text. '' on any
    failure."""
    dest = download_slides(talk)
    if not dest:
        return ""
    from .deep_read import extract_pdf_text
    return extract_pdf_text(dest, max_chars=max_chars)


def run_slides(
    *,
    talk_ids: list[str] | None = None,
    force: bool = False,
    dry_run: bool = False,
) -> int:
    """Download slide decks for the selected talks. Returns how many are available
    locally afterwards."""
    _, talks = load_talks()
    talks = _selected(talks, talk_ids)
    have = [t for t in talks if t.slides]
    log.info("%d/%d selected talk(s) have a slides URL", len(have), len(talks))
    if dry_run:
        for t in have:
            log.info("  %s — %s", t.id, "cached" if slides_path(t.id).exists() else "to download")
        return 0
    delay = float(os.environ.get("TALKS_SLIDES_DELAY", "1"))
    ok = fail = 0
    for i, t in enumerate(have, 1):
        if slides_path(t.id).exists() and not force:
            ok += 1
            continue
        log.info("slides %d/%d: %s", i, len(have), t.id)
        if download_slides(t, force=force):
            ok += 1
        else:
            fail += 1
        time.sleep(delay)
    log.info("slides: %d available locally, %d failed (of %d with a URL)", ok, fail, len(have))
    return ok


def ground_truth_context(talk: Talk) -> str:
    """Authoritative, ASR-error-free material to read *alongside* the transcript:
    the talk's OCIS abstract, its arXiv paper abstract(s), and its slide deck.
    All best-effort (arXiv + slides are fetched live; failures are skipped)."""
    blocks: list[str] = []
    if talk.abstract:
        blocks.append(
            "## 报告摘要（来源页面官方，权威、无 ASR 错误——据此校正转写里听错的"
            "标题 / 人名 / 术语）\n" + talk.abstract
        )
    for pid in talk.papers or []:
        if not _is_arxiv_id(pid):
            continue
        try:
            p = fetch_arxiv_by_id(pid)
        except Exception:  # noqa: BLE001
            p = None
        if p and p.abstract:
            authors = ", ".join(p.authors[:8]) + (" et al." if len(p.authors) > 8 else "")
            blocks.append(
                f"## 对应论文摘要（arXiv {pid}，权威）\nTitle: {p.title}\n"
                f"Authors: {authors}\nAbstract: {p.abstract}"
            )
    try:
        slides = fetch_slides_text(talk)
    except Exception:  # noqa: BLE001
        slides = ""
    if slides:
        blocks.append(
            "## 讲者幻灯片（文字抽取，权威——含报告的结构 / 公式 / 关键结果，"
            "可能有 OCR/排版噪声）\n" + slides
        )
    return "\n\n".join(blocks)


def read_talk(
    client: "SJTUClient",
    talk: Talk,
    transcript: str,
    interests_text: str,
    *,
    model: str | None = None,
    segment_title: str | None = None,
    segment_speaker: str | None = None,
) -> str:
    """Return a Markdown reading-note body for one talk (empty on failure)."""
    context = ground_truth_context(talk)
    if context:
        log.info("talk %s: attached ground-truth abstract(s) (%d chars)", talk.id, len(context))
    user = build_user_message(
        talk, transcript, interests_text, context=context,
        segment_title=segment_title, segment_speaker=segment_speaker,
    )
    try:
        result = client.chat(
            [
                {"role": "system", "content": TALK_READ_SYSTEM},
                {"role": "user", "content": user},
            ],
            model=model,
            max_tokens=TALK_READ_MAX_TOKENS,
        )
        log.info("talk read LLM call succeeded for %s (%d chars)", talk.id, len(result))
        return result
    except Exception as e:  # noqa: BLE001
        log.error("talk read FAILED for %s (all retries exhausted): %s", talk.id, e)
        return ""


# ── render ────────────────────────────────────────────────────────────────────

def _render_talk_page(
    talk: Talk,
    content: str,
    run_date: date,
    *,
    file_id: str,
    paper_links: list[dict],
    segment_title: str | None = None,
    segment_speaker: str | None = None,
) -> Path:
    TALKS_DIR.mkdir(parents=True, exist_ok=True)
    out = TALKS_DIR / f"{run_date.isoformat()}-{_slug(file_id)}.md"
    title = segment_title or talk.title or talk.id
    speaker = segment_speaker or talk.speaker
    topic_label = TOPIC_LABELS_ZH.get(talk.topic or "other", talk.topic or "other")

    lines = [f"# {title}\n"]
    if speaker:
        lines.append(f"**讲者**: {speaker}  ")
    if talk.discussant:
        lines.append(f"**讨论人**: {talk.discussant}  ")
    if talk.venue:
        lines.append(f"**来源**: {talk.venue}  ")
    if talk.date:
        lines.append(f"**日期**: {talk.date}  ")
    lines.append(f"**主题**: {topic_label}  ")
    video_line = f"**视频**: <{talk.url}>"
    if talk.slides:
        video_line += f" · [幻灯片]({talk.slides})"
    lines.append(video_line + "\n")
    if talk.abstract:
        lines.append(f"> **官方摘要**：{talk.abstract}\n")
    lines.append(
        "> 本页据讲座录音的自动转写（ASR）生成。**人名 / 术语 / 公式 / 具体的率与界可能被听错**，"
        "关键处请对照视频或讲者论文核对。\n"
    )
    lines.extend(_paper_links_md(paper_links))
    lines += [
        "---\n",
        content if content else "*（讲座精读失败，请查看日志）*",
        f"\n---\n\nMaintained by 陈星宇 · "
        f"[Homepage]({HOMEPAGE_URL}) · [Source on GitHub]({REPO_URL})\n",
    ]
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out


# ── index + archive ───────────────────────────────────────────────────────────

def _load_index() -> list[dict]:
    if not TALKS_INDEX.exists():
        return []
    try:
        data = json.loads(TALKS_INDEX.read_text(encoding="utf-8"))
        return data if isinstance(data, list) else []
    except Exception:
        return []


def _update_index(new_entries: list[dict]) -> None:
    """Upsert talk entries (keyed by id) into data/talks_index.json, newest run
    wins, then refresh docs/all_talks.md."""
    by_id = {e["id"]: e for e in _load_index()}
    for e in new_entries:
        by_id[e["id"]] = e
    merged = sorted(
        by_id.values(),
        key=lambda e: (e.get("date") or "", e.get("id") or ""),
        reverse=True,
    )
    TALKS_INDEX.parent.mkdir(parents=True, exist_ok=True)
    TALKS_INDEX.write_text(json.dumps(merged, ensure_ascii=False, indent=2), encoding="utf-8")
    _write_archive(merged)


def _write_archive(entries: list[dict]) -> None:
    """Refresh docs/all_talks.md (linked from the site nav), grouped by venue."""
    lines = [
        "# 讲座精读\n",
        "会议 / seminar 录像（如 OCIS、INI workshop）转写后，按 deep-read 风格读成结构化笔记："
        "工作线背景、最小内核、报告主体、对应论文与开放问题。**不打分、不排名**；"
        "因来自自动转写，技术细节请对照视频 / 论文核对。\n",
    ]
    by_venue: dict[str, list[dict]] = {}
    for e in entries:
        by_venue.setdefault(e.get("venue") or "其他", []).append(e)
    for venue in sorted(by_venue):
        lines.append(f"## {venue}\n")
        for e in sorted(by_venue[venue], key=lambda e: e.get("date") or "", reverse=True):
            doc_path = e.get("doc_path")
            if not doc_path:
                continue
            bits = []
            if e.get("speaker"):
                bits.append(e["speaker"])
            if e.get("date"):
                bits.append(e["date"])
            topic_label = TOPIC_LABELS_ZH.get(e.get("topic", "other"), e.get("topic", "other"))
            bits.append(topic_label)
            meta = " · ".join(bits)
            lines.append(f"- [{e.get('title') or e['id']}]({doc_path})  \n  {meta}")
        lines.append("")
    lines.append(
        f"\n---\n\nMaintained by 陈星宇 · [Homepage]({HOMEPAGE_URL}) · [Source]({REPO_URL})\n"
    )
    (DOCS_DIR / "all_talks.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


