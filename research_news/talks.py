def _selected(talks: list[Talk], ids: list[str] | None) -> list[Talk]:
    if not ids:
        return talks
    want = set(ids)
    out = [t for t in talks if t.id in want]
    missing = want - {t.id for t in out}
    for m in missing:
        log.warning("no talk with id %r in config", m)
    return out


def run_ingest(
    *,
    talk_ids: list[str] | None = None,
    model_size: str = "large-v3",
    prefer_subs: bool = False,
    subs_file: str | None = None,
    force: bool = False,
    dry_run: bool = False,
) -> list[Path]:
    asr_default, talks = load_talks()
    talks = _selected(talks, talk_ids)
    if subs_file and len(talks) != 1:
        log.error("--subs-file expects exactly one --id (got %d talks)", len(talks))
        return []
    if dry_run:
        for t in talks:
            status = "has transcript" if transcript_path(t.id).exists() else "needs transcript"
            log.info("  %s — %s (%s)", t.id, t.title or t.url, status)
        return []
    # Space out caption fetches so YouTube doesn't 429 a long --prefer-subs batch.
    subs_delay = float(os.environ.get("TALKS_SUBS_DELAY", "2"))
    out: list[Path] = []
    for i, t in enumerate(talks, 1):
        already = transcript_path(t.id).exists()
        log.info("ingest %d/%d: %s", i, len(talks), t.id)
        try:
            p = ingest(t, asr_default, model_size=model_size,
                       prefer_subs=prefer_subs, subs_file=subs_file, force=force)
            if p:
                out.append(p)
        except Exception as e:  # noqa: BLE001
            log.error("ingest failed for %s: %s", t.id, e)
        if prefer_subs and not already and i < len(talks):
            time.sleep(subs_delay)
    return out


def run_read(
    *,
    talk_ids: list[str] | None = None,
    model: str | None = None,
    read_papers: bool = False,
    force: bool = False,
    dry_run: bool = False,
) -> list[Path]:
    model = model or TALK_MODEL
    _, talks = load_talks()
    talks = _selected(talks, talk_ids)
    done = {e.get("talk_id") for e in _load_index()}

    pending: list[Talk] = []
    for t in talks:
        if not transcript_path(t.id).exists():
            log.info("skip %s: no transcript yet (run `talks ingest --id %s`)", t.id, t.id)
            continue
        if t.id in done and not force:
            log.info("skip %s: already read (use --force to re-read)", t.id)
            continue
        pending.append(t)

    if dry_run:
        for t in pending:
            n_seg = len(t.segments) or 1
            log.info("  would read %s — %s (%d note%s)",
                     t.id, t.title or t.url, n_seg, "" if n_seg == 1 else "s")
        return []
    if not pending:
        log.info("no talks ready to read")
        return []

    from dotenv import load_dotenv

    from .llm.sjtu_client import SJTUClient
    from .render.markdown import update_index
    load_dotenv()
    interests_text = INTERESTS_CONFIG.read_text(encoding="utf-8")
    client = SJTUClient()

    written: list[Path] = []
    index_entries: list[dict] = []
    for t in pending:
        if read_papers and t.papers:
            try:
                read_linked_papers(client, t, interests_text, run_date=talk_date(t))
            except Exception as e:  # noqa: BLE001
                log.warning("read_linked_papers failed for %s: %s", t.id, e)

        links = resolve_paper_links(t)
        run_date = talk_date(t)
        transcript = transcript_path(t.id).read_text(encoding="utf-8")
        chunks = tr.split_by_segments(transcript, t.segments)
        multi = len(chunks) > 1

        for i, chunk in enumerate(chunks, 1):
            file_id = f"{t.id}-{i}" if multi else t.id
            seg_title = chunk.get("title")
            seg_speaker = chunk.get("speaker")
            label = seg_title or t.title or t.id
            log.info("reading talk %s%s ...", t.id, f" [{i}/{len(chunks)}]" if multi else "")
            content = read_talk(
                client, t, chunk["text"], interests_text, model=model,
                segment_title=seg_title, segment_speaker=seg_speaker,
            )
            page = _render_talk_page(
                t, content, run_date, file_id=file_id, paper_links=links,
                segment_title=seg_title, segment_speaker=seg_speaker,
            )
            written.append(page)
            index_entries.append({
                "id": file_id,
                "talk_id": t.id,
                "date": run_date.isoformat(),
                "title": label,
                "speaker": seg_speaker or t.speaker,
                "venue": t.venue,
                "topic": t.topic or "other",
                "url": t.url,
                "doc_path": f"talks/{page.name}",
                "papers": [lk["id"] for lk in links],
            })
            log.info("wrote %s", page)

    if index_entries:
        _update_index(index_entries)
        try:
            update_index()  # refresh homepage + archive nav so the talk shows up
        except Exception as e:  # noqa: BLE001
            log.warning("homepage index refresh failed: %s", e)
    return written


def _print_list() -> None:
    _, talks = load_talks()
    if not talks:
        print("no talks in config/talks.yaml")
        return
    dr_index = _load_index()
    have_page = {e.get("talk_id") for e in dr_index}
    print(f"{len(talks)} talk(s) in config/talks.yaml:\n")
    for t in talks:
        tx = "✓" if transcript_path(t.id).exists() else "·"
        pg = "✓" if t.id in have_page else "·"
        print(f"  [{tx} transcript] [{pg} page]  {t.id}")
        print(f"      {t.title or '(no title)'} — {t.speaker or '?'} @ {t.venue or '?'}")


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    # The HuggingFace model download spams INFO-level httpx request lines; keep
    # the console focused on ingest/transcribe progress.
    for noisy in ("httpx", "httpcore", "huggingface_hub", "urllib3", "filelock"):
        logging.getLogger(noisy).setLevel(logging.WARNING)
    ap = argparse.ArgumentParser(
        description="Conference talk pipeline: transcribe lectures and read them into notes.")
    sub = ap.add_subparsers(dest="cmd", required=True)

    sub.add_parser("list", help="show every talk + its transcript/page status")

    p_ing = sub.add_parser("ingest", help="download + transcribe (local; needs [asr] extra + ffmpeg)")
    p_ing.add_argument("--id", action="append", default=[], help="talk id (repeatable); omit with --all")
    p_ing.add_argument("--all", action="store_true", help="ingest every talk missing a transcript")
    p_ing.add_argument("--model-size", default=os.environ.get("WHISPER_MODEL", "large-v3"),
                       help="faster-whisper model (default large-v3; on a 4GB GPU use "
                            "distil-large-v3 or small). Override default via $WHISPER_MODEL")
    p_ing.add_argument("--prefer-subs", action="store_true",
                       help="use the video's existing (auto)captions if present, skip ASR")
    p_ing.add_argument("--subs-file",
                       help="ingest an existing .srt/.vtt (e.g. from whisper.cpp) instead of "
                            "running ASR; needs a single --id")
    p_ing.add_argument("--force", action="store_true", help="re-transcribe even if a transcript exists")
    p_ing.add_argument("--dry-run", action="store_true", help="list what would be ingested")

    p_rd = sub.add_parser("read", help="LLM-read transcripts into docs/talks/ notes")
    p_rd.add_argument("--id", action="append", default=[], help="talk id (repeatable); omit with --all")
    p_rd.add_argument("--all", action="store_true", help="read every transcript missing a page")
    p_rd.add_argument("--read-papers", action="store_true",
                      help="also deep-read the talk's linked arXiv papers (so cross-links resolve)")
    p_rd.add_argument("--model", default=None, help="override the read model")
    p_rd.add_argument("--force", action="store_true", help="re-read even if a page exists")
    p_rd.add_argument("--dry-run", action="store_true", help="list what would be read, no LLM")

    p_sl = sub.add_parser("slides", help="download talk slide decks to data/talks/slides/ (local)")
    p_sl.add_argument("--id", action="append", default=[], help="talk id (repeatable); omit with --all")
    p_sl.add_argument("--all", action="store_true", help="download every talk's slides")
    p_sl.add_argument("--force", action="store_true", help="re-download even if cached")
    p_sl.add_argument("--dry-run", action="store_true", help="list what has slides, download nothing")

    p_oc = sub.add_parser("import-ocis",
                          help="import the OCIS catalog → config/talks.ocis.yaml (local)")
    p_oc.add_argument("--season", action="append", default=[],
                      help="season slug, e.g. spring-2024 (repeatable)")
    p_oc.add_argument("--all-seasons", action="store_true",
                      help="try every season page from 2020 to now (404s skipped)")
    p_oc.add_argument("--url", action="append", default=[], help="explicit page URL (repeatable)")
    p_oc.add_argument("--html", action="append", default=[],
                      help="parse a saved page HTML file instead of fetching (repeatable)")
    p_oc.add_argument("--catalog-only", action="store_true",
                      help="write data/ocis_catalog.json but not talks.ocis.yaml")
    p_oc.add_argument("--llm", action="store_true",
                      help="use the LLM to associate links (default: deterministic, offline)")
    p_oc.add_argument("--limit", type=int, default=None, help="cap number of talks (testing)")
    p_oc.add_argument("--model", default=None, help="override the extraction model")
    p_oc.add_argument("--dry-run", action="store_true",
                      help="fetch + count candidate links, no LLM, no write")

    args = ap.parse_args()

    if args.cmd == "list":
        _print_list()
        return

    if args.cmd == "slides":
        ids = list(args.id) or None
        if not ids and not args.all:
            ap.error("pass --id <id> (repeatable) or --all")
        n = run_slides(talk_ids=ids, force=args.force, dry_run=args.dry_run)
        print(f"slides available locally: {n}")
        return

    if args.cmd == "import-ocis":
        from .scrapers import ocis
        urls = list(args.url) + [ocis.season_url(s) for s in args.season]
        if args.all_seasons:
            urls += ocis.default_season_urls()
        if not urls and not args.html:
            ap.error("pass --season <slug>, --url <URL>, --html <file>, or --all-seasons")
        rows = ocis.import_pages(
            urls=urls or None, html_files=list(args.html) or None,
            model=args.model, catalog_only=args.catalog_only,
            limit=args.limit, dry_run=args.dry_run, use_llm=args.llm,
        )
        print(f"OCIS: extracted {len(rows)} talk row(s)")
        return

    ids = list(args.id) or None
    if not ids and not args.all:
        ap.error("pass --id <id> (repeatable) or --all")

    if args.cmd == "ingest":
        paths = run_ingest(talk_ids=ids, model_size=args.model_size,
                           prefer_subs=args.prefer_subs, subs_file=args.subs_file,
                           force=args.force, dry_run=args.dry_run)
        print(f"ingested {len(paths)} transcript(s)")
    elif args.cmd == "read":
        paths = run_read(talk_ids=ids, model=args.model, read_papers=args.read_papers,
                         force=args.force, dry_run=args.dry_run)
        print(f"wrote {len(paths)} talk page(s)")


if __name__ == "__main__":
    main()
