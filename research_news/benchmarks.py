"""AI evaluation / benchmark track.

Two entry points share one pipeline:

- **Conference proceedings** (``collect → score → summarize → render``): every
  enabled venue in ``config/benchmarks.yaml`` is reduced to its evaluation /
  benchmark papers, scored against ``config/interests.benchmark.yaml``, the top
  ones are annotated, and the result is rendered as a journal-like section with
  one page per topic (``docs/benchmarks/<venue>/``).
- **Daily arXiv radar** (``daily``): the same filter + scoring over today's
  cs.CL / cs.LG submissions, rendered to ``docs/benchmarks/daily/<date>.md``.

Design constraints (see ops/design/2026-11-10-ai-llm-coverage-plan.md):

- The conference pool is 4,000–6,500 papers per venue, so a zero-LLM title
  prefilter runs first; abstract pages are fetched only for survivors.
- Everything is resumable: ``papers.json`` is the state, scored papers are
  skipped on re-runs, and summaries are saved incrementally.
- LLM throughput is ~9 requests/minute, so scoring/summarizing is capped per
  run and meant to be run in the background / over several nights.
"""
