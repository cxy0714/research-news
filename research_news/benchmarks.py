log = logging.getLogger("research_news.benchmarks")

CONFIG_PATH = Path("config/benchmarks.yaml")
INTERESTS_PATH = Path("config/interests.benchmark.yaml")
DATA_ROOT = Path("data/benchmarks")
DOCS_ROOT = Path("docs/benchmarks")
DAILY_DIR = DOCS_ROOT / "daily"
MKDOCS = Path("mkdocs.yml")
NAV_START = "# BENCH-NAV-START (auto-generated by `python -m research_news.benchmarks render` — do not edit between markers)"
NAV_END = "# BENCH-NAV-END"

_PAPER_FIELDS = {f.name for f in dataclasses.fields(Paper)}


# ── config / state ───────────────────────────────────────────────────────────

def load_config() -> dict:
    return yaml.safe_load(CONFIG_PATH.read_text(encoding="utf-8"))


def load_interests() -> tuple[str, dict]:
    text = INTERESTS_PATH.read_text(encoding="utf-8")
    return text, (yaml.safe_load(text) or {})


def venue_cfg(cfg: dict, venue_id: str) -> dict:
    for v in cfg.get("venues", []):
        if v["id"] == venue_id:
            return v
    raise KeyError(f"unknown venue: {venue_id}")


def _venue_dir(vid: str) -> Path:
    return DATA_ROOT / vid


def load_papers(vid: str) -> list[Paper]:
    p = _venue_dir(vid) / "papers.json"
    if not p.exists():
        return []
    raw = json.loads(p.read_text(encoding="utf-8"))
    return [Paper(**{k: v for k, v in d.items() if k in _PAPER_FIELDS}) for d in raw]


def save_papers(vid: str, papers: list[Paper]) -> None:
    d = _venue_dir(vid)
    d.mkdir(parents=True, exist_ok=True)
    (d / "papers.json").write_text(
        json.dumps([p.to_dict() for p in papers], ensure_ascii=False, indent=1),
        encoding="utf-8",
    )


def save_meta(vid: str, meta: dict) -> None:
    d = _venue_dir(vid)
    d.mkdir(parents=True, exist_ok=True)
    (d / "meta.json").write_text(json.dumps(meta, ensure_ascii=False, indent=1), encoding="utf-8")


def load_meta(vid: str) -> dict:
    p = _venue_dir(vid) / "meta.json"
    if not p.exists():
        return {}
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except Exception:  # noqa: BLE001
        return {}


# ── collection ───────────────────────────────────────────────────────────────

def _compile(patterns: list[str]) -> list[re.Pattern]:
    return [re.compile(p, re.I) for p in patterns]


def _matches(title: str, abstract: str, filt: dict) -> bool:
    """Title-only by default.

    Abstract matching was tried and rejected: in NLP volumes almost every
    abstract says "we evaluate on ...", which pulled in 60%+ of the venue.
    Benchmark *papers* announce themselves in the title (benchmark / evaluation
    / leaderboard / judge / contamination ...), so the title is the signal.
    """
    if any(r.search(title) for r in _compile(filt.get("deny_title_patterns", []))):
        return False
    return any(r.search(title) for r in _compile(filt.get("title_patterns", [])))


def _norm_title(t: str) -> str:
    return re.sub(r"[^a-z0-9]+", " ", t.lower()).strip()


def _acl_track(vol: str) -> str:
    tail = vol.split(".", 1)[-1]
    return {
        "acl-long": "Long", "acl-short": "Short",
        "emnlp-main": "Main", "findings-acl": "Findings",
    }.get(tail, tail)


def collect(vcfg: dict, cfg: dict, *, force: bool = False) -> list[Paper]:
    vid = vcfg["id"]
    if not force:
        existing = load_papers(vid)
        if existing:
            log.info("[%s] reusing %d collected papers (use --force to re-crawl)", vid, len(existing))
            return existing

    adapter = vcfg["adapter"]
    papers: list[Paper] = []
    if adapter == "pmlr":
        papers = proc.pmlr_volume(
            vcfg["volume"], venue_id=vid, label=vcfg["label"], track=vcfg.get("track", "Main")
        )
    elif adapter == "acl":
        for vol in vcfg.get("volumes", []):
            papers.extend(
                proc.acl_volume(vol, venue_id=vid, label=vcfg["label"], track=_acl_track(vol))
            )
    elif adapter == "cvf":
        papers = proc.cvf_conference(
            vcfg["conference"], int(vcfg["year"]), venue_id=vid, label=vcfg["label"]
        )
    elif adapter == "aaai":
        papers = proc.aaai_year(int(vcfg["year"]), venue_id=vid, label=vcfg["label"])
    elif adapter == "neurips":
        papers = proc.neurips_year(
            int(vcfg["year"]), venue_id=vid, label=vcfg["label"],
            href_must_contain=vcfg.get("href_must_contain"),
        )
    else:
        raise ValueError(f"unknown adapter: {adapter}")

    filt = cfg.get("filter", {})
    cap = int(cfg.get("limits", {}).get("max_candidates_per_venue", 900))
    candidates = [p for p in papers if _matches(p.title, p.abstract, filt)]
    candidates.sort(key=lambda p: p.title.lower())
    candidates = candidates[:cap]
    log.info("[%s] %d/%d papers pass the prefilter (cap %d)",
             vid, len(candidates), len(papers), cap)

    if adapter in {"pmlr", "cvf", "aaai", "neurips"}:
        log.info("[%s] fetching abstracts for %d candidates ...", vid, len(candidates))
        proc.enrich_abstracts(candidates, adapter=adapter)

    # Drop papers we cannot score, dedupe by title.
    seen: set[str] = set()
    cleaned: list[Paper] = []
    for p in candidates:
        key = _norm_title(p.title)
        if not key or key in seen or not p.abstract:
            continue
        seen.add(key)
        cleaned.append(p)

    save_papers(vid, cleaned)
    log.info("[%s] collected %d candidates (%d with abstracts)", vid, len(cleaned),
             sum(1 for p in cleaned if p.abstract))
    return cleaned


# ── scoring / summarizing ────────────────────────────────────────────────────

def score_venue(vid: str, cfg: dict, *, max_n: int | None = None,
                model: str | None = None, force: bool = False) -> int:
    papers = load_papers(vid)
    todo = [p for p in papers if force or p.score is None]
    if max_n is not None:
        todo = todo[:max_n]
    if not todo:
        log.info("[%s] nothing to score", vid)
        return 0
    interests_text, _ = load_interests()
    client = SJTUClient()
    log.info("[%s] scoring %d papers ...", vid, len(todo))
    scores = score_papers(
        client, todo, interests_text, model=model, system_prompt=BENCH_SCORE_SYSTEM
    )
    for p in todo:
        if p.paper_id in scores:
            p.score, p.score_reason = scores[p.paper_id]
        else:
            p.score = p.score if p.score is not None else 0.0
            p.score_reason = p.score_reason or "scoring failed (no LLM result)"
    save_papers(vid, papers)
    usage_report(client, f"benchmarks:{vid}")
    log.info("[%s] scored %d/%d", vid, len(scores), len(todo))
    return len(scores)


def summarize_venue(vid: str, cfg: dict, *, max_n: int | None = None,
                    model: str | None = None) -> int:
    papers = load_papers(vid)
    _, icfg = load_interests()
    th_show = float(icfg.get("score_threshold_show", 4))
    cap = max_n if max_n is not None else int(icfg.get("max_summaries_per_venue", 90))
    todo = [
        p for p in sorted(papers, key=lambda x: x.score or 0, reverse=True)
        if (p.score or 0) >= th_show and not p.summary_zh
    ][:cap]
    if not todo:
        log.info("[%s] nothing to summarize", vid)
        return 0
    interests_text, _ = load_interests()
    client = SJTUClient()
    log.info("[%s] summarizing %d papers ...", vid, len(todo))
    for i, p in enumerate(todo, 1):
        try:
            summarize_paper(
                client, p, interests_text,
                model=model,
                system_prompt=BENCH_SUMMARY_SYSTEM,
                topics=BENCH_TOPICS,
            )
        except Exception as e:  # noqa: BLE001
            log.warning("summary failed for %s: %s", p.paper_id, e)
        if i % 5 == 0:
            save_papers(vid, papers)
            log.info("  summarized %d/%d", i, len(todo))
    save_papers(vid, papers)
    usage_report(client, f"benchmarks:{vid}")
    return len([p for p in todo if p.summary_zh])


# ── rendering ────────────────────────────────────────────────────────────────

def _track_label(p: Paper) -> str:
    """Normalise the ACL-family volume tail into a display track name."""
    return {
        "acl-long": "Long", "acl-short": "Short",
        "emnlp-main": "Main", "findings-acl": "Findings",
    }.get(p.venue_track, p.venue_track)


def _link(p: Paper) -> str:
    bits: list[str] = []
    if p.proceedings_url or p.url:
        bits.append(f"[论文页]({p.proceedings_url or p.url})")
    if p.pdf_url:
        bits.append(f"[PDF]({p.pdf_url})")
    if p.arxiv_id:
        bits.append(f"[arXiv](https://arxiv.org/abs/{p.arxiv_id})")
    if p.openreview_id:
        bits.append(f"[OpenReview](https://openreview.net/forum?id={p.openreview_id})")
    return " · ".join(bits)


def card(p: Paper, n: int, *, show_venue: bool = True) -> list[str]:
    out = [f"### {n}. {p.title}"]
    if link := _link(p):
        out.append(f"- **链接**: {link}")
    authors = ", ".join(p.authors[:8]) + (" et al." if len(p.authors) > 8 else "")
    if authors:
        out.append(f"- **作者**: {authors}")
    venue = p.venue or p.source
    if show_venue and venue:
        track = f" · {_track_label(p)}" if p.venue_track else ""
        out.append(f"- **会议/来源**: {venue}{track}")
    meta: list[str] = []
    if p.score is not None:
        meta.append(f"相关性 {p.score:.0f}/10")
    if p.bench_type:
        meta.append(f"`{p.bench_type}`")
    if meta:
        out.append("- " + " · ".join(meta))
    if p.what_it_measures:
        out.append(f"- **测什么**: {p.what_it_measures}")
    if p.summary_zh:
        out.append(f"- **摘要**: {p.summary_zh}")
    if p.why_relevant:
        out.append(f"- **为什么值得看**: {p.why_relevant}")
    if p.key_techniques:
        out.append("- **关键技术**: " + ", ".join(f"`{k}`" for k in p.key_techniques))
    return out


def _paged(name: str, items: list[Paper], size: int) -> list[tuple[str, list[Paper]]]:
    """Split one topic's papers into pages of `size`; first page keeps the name."""
    if not items:
        return []
    pages = []
    for i in range(0, len(items), size):
        suffix = "" if i == 0 else f"-{i // size + 1}"
        pages.append((f"{name}{suffix}.md", items[i:i + size]))
    return pages


def _is_bench(p: Paper) -> bool:
    return bool(p.score is not None and p.score >= 0)


def _topic_groups(papers: list[Paper]) -> dict[str, list[Paper]]:
    groups: dict[str, list[Paper]] = {}
    for p in papers:
        t = p.topic if p.topic in BENCH_TOPICS else "other"
        groups.setdefault(t, []).append(p)
    for items in groups.values():
        items.sort(key=lambda x: x.score or 0, reverse=True)
    return groups


def _write(path: Path, lines: list[str]) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    return path


def render_venue(vid: str, cfg: dict) -> Path:
    vcfg = venue_cfg(cfg, vid)
    _, icfg = load_interests()
    size = int(icfg.get("page_size", 40))
    papers = load_papers(vid)
    scored = [p for p in papers if p.score is not None]
    summarized = [p for p in scored if p.summary_zh]
    topic_pages: dict[str, list[str]] = {}

    groups = _topic_groups(summarized)
    for topic in BENCH_TOPICS:
        items = groups.get(topic, [])
        for fname, chunk in _paged(topic, items, size):
            label = BENCH_TOPIC_LABELS_ZH.get(topic, topic)
            lines = [
                f"# {vcfg['label']} · {label}",
                "",
                f"> 本页 {len(chunk)} 篇（该主题共 {len(items)} 篇），按相关性排序。"
                f" [返回总览](../index.md)",
                "",
            ]
            for i, p in enumerate(chunk, 1):
                lines.extend(card(p, i))
                lines.append("")
            _write(DOCS_ROOT / vid / "topics" / fname, lines)
            topic_pages.setdefault(topic, []).append(f"topics/{fname}")

    # ── all-papers compact table (paginated) ────────────────────────────────
    # score 0 = the model judged it "not actually about evaluation"; listing
    # those would bury the useful rows under keyword false positives.
    all_pages: list[str] = []
    table_size = 150
    listed = [p for p in scored if (p.score or 0) >= 1]
    ordered = sorted(listed, key=lambda p: p.score or 0, reverse=True)
    for i in range(0, max(len(ordered), 1), table_size):
        chunk = ordered[i:i + table_size]
        fname = "all.md" if i == 0 else f"all-{i // table_size + 1}.md"
        lines = [
            f"# {vcfg['label']} · 全部收录（{len(ordered)} 篇）",
            "",
            "> 仅列出通过预过滤且已打分的论文；分数是「评测方法学价值」，不是会议录用质量。"
            " [返回总览](index.md)",
            "",
            "| # | 论文 | 轨道 | 分数 | 链接 |",
            "|---:|---|---|---:|---|",
        ]
        for n, p in enumerate(chunk, i + 1):
            title = p.title.replace("|", "\\|")
            links = []
            if p.url:
                links.append(f"[页]({p.url})")
            if p.pdf_url:
                links.append(f"[PDF]({p.pdf_url})")
            lines.append(
                f"| {n} | {title} | {_track_label(p) or '-'} | "
                f"{p.score:.0f} | {' · '.join(links) or '-'} |"
            )
        _write(DOCS_ROOT / vid / fname, lines)
        all_pages.append(fname)

    # ── venue index ─────────────────────────────────────────────────────────
    lines: list[str] = [
        f"# {vcfg['label']} · AI 评测 / Benchmark",
        "",
        f"> 只收录与「评测 / benchmark」相关的论文：标题命中评测词表（ACL 系另加摘要）后，"
        f"按**评测方法学价值**打分，取高分做中文精摘。**不是会议全量**。",
        "",
        f"- 收录 **{len(papers)}** 篇 · 已打分 **{len(scored)}** · 精摘 **{len(summarized)}** · "
        f"更新于 {date.today().isoformat()}",
        "- 口径：测量设计 / 构念覆盖 / 污染控制 / 难度校准 / 人类基线 / judge 验证 / 统计可靠性；"
        "纯榜单提升不加分。",
        "",
        "## 主题分布",
        "",
        "| 主题 | 精摘篇数 | 页面 |",
        "|---|---:|---|",
    ]
    for topic in BENCH_TOPICS:
        items = groups.get(topic, [])
        if not items:
            continue
        links = " · ".join(f"[{i + 1}]({u})" for i, u in enumerate(topic_pages.get(topic, [])))
        lines.append(f"| {BENCH_TOPIC_LABELS_ZH.get(topic, topic)} | {len(items)} | {links} |")
    lines += ["", "## 必读 Top 20", ""]
    for i, p in enumerate(sorted(summarized, key=lambda x: x.score or 0, reverse=True)[:20], 1):
        lines.extend(card(p, i))
        lines.append("")
    lines += [
        "## 全部收录",
        "",
        f"共 {len(ordered)} 篇，按分数排序："
        + " · ".join(f"[{i + 1}]({u})" for i, u in enumerate(all_pages)),
        "",
    ]
    out = _write(DOCS_ROOT / vid / "index.md", lines)
    save_meta(vid, {
        "label": vcfg["label"],
        "papers": len(papers),
        "scored": len(scored),
        "summarized": len(summarized),
        "updated": date.today().isoformat(),
    })
    log.info("[%s] rendered %s (%d papers, %d summaries)", vid, out, len(papers), len(summarized))
    return out


def render_index(cfg: dict) -> Path:
    rows: list[str] = []
    for v in cfg.get("venues", []):
        if not v.get("enabled", True):
            continue
        meta = load_meta(v["id"])
        if not meta:
            continue
        rows.append(
            f"| [{v['label']}]({v['id']}/index.md) | {meta.get('papers', 0)} | "
            f"{meta.get('scored', 0)} | {meta.get('summarized', 0)} |"
        )
    daily = sorted(DAILY_DIR.glob("*.md")) if DAILY_DIR.exists() else []
    daily = [d for d in daily if d.name != "index.md"]
    lines = [
        "# AI 评测 / Benchmark",
        "",
        "> 两条线：**会议专题**（每届会议一个分区，按主题分页）+ **每日雷达**"
        "（arXiv cs.CL / cs.LG 当天的评测论文）。只关心评测方法学，不追榜单。",
        "",
        "## 会议专题",
        "",
        "| 会议 | 收录 | 已打分 | 精摘 |",
        "|---|---:|---:|---:|",
        *rows,
        "",
        "## 每日雷达",
        "",
    ]
    if daily:
        for d in sorted(daily, reverse=True)[:30]:
            lines.append(f"- [{d.stem}](daily/{d.name})")
    else:
        lines.append("*（还没有每日页面）*")
    lines += [
        "",
        "## 收录口径",
        "",
        "- 会议：NeurIPS / ICML / ICLR / ACL 系 / CVPR / AAAI 等**开放获取**的 proceedings；"
        "当前用标题词表预过滤，再让 LLM 按评测方法学打分。",
        "- 每日：arXiv `cs.CL` / `cs.LG` 当天提交，同一套词表 + 同一套打分。",
        "- 分数是「值不值得为评测方法学读」，不是论文录用质量；纯 SOTA 榜单不加分。",
    ]
    return _write(DOCS_ROOT / "index.md", lines)


def render_nav(cfg: dict) -> None:
    if not MKDOCS.exists():
        return
    text = MKDOCS.read_text(encoding="utf-8")
    if NAV_START not in text or NAV_END not in text:
        log.warning("nav markers missing in mkdocs.yml; skipping nav update")
        return
    block = [NAV_START, "  - AI 评测:", "    - 总览: benchmarks/index.md"]
    if (DAILY_DIR / "index.md").exists():
        block.append("    - 每日雷达: benchmarks/daily/index.md")
    for v in cfg.get("venues", []):
        if not v.get("enabled", True):
            continue
        if (DOCS_ROOT / v["id"] / "index.md").exists():
            block.append(f"    - {v['label']}: benchmarks/{v['id']}/index.md")
    block.append(NAV_END)
    new = re.sub(
        re.escape(NAV_START) + r".*?" + re.escape(NAV_END),
        "\n".join(block),
        text,
        flags=re.S,
    )
    if new != text:
        MKDOCS.write_text(new, encoding="utf-8")
        log.info("updated AI-benchmark nav in mkdocs.yml")


# ── daily arXiv radar ────────────────────────────────────────────────────────

def _write_daily_index() -> Path:
    DAILY_DIR.mkdir(parents=True, exist_ok=True)
    idx = ["# 每日 AI 评测雷达", "", "> 每天从 arXiv cs.CL / cs.LG 的提交里筛评测 / benchmark，"
           "按方法学价值打分并精摘。", ""]
    for f in sorted(DAILY_DIR.glob("*.md"), reverse=True):
        if f.name == "index.md":
            continue
        idx.append(f"- [{f.stem}]({f.name})")
    return _write(DAILY_DIR / "index.md", idx)


def daily(for_date: date | None = None, *, model: str | None = None,
          dry_run: bool = False) -> Path | None:
    cfg = load_config()
    dcfg = cfg.get("daily", {})
    when = for_date or date.today()
    arxiv_cfg = {
        "categories": dcfg.get("categories", ["cs.CL", "cs.LG"]),
        "include_cross_listed": False,
        "max_per_category": 400,
    }
    papers = fetch_arxiv(arxiv_cfg, for_date=when if when != date.today() else None)
    log.info("[daily %s] fetched %d arXiv papers", when, len(papers))
    filt = cfg.get("filter", {})
    cands = [p for p in papers if _matches(p.title, p.abstract, filt)]
    seen: set[str] = set()
    uniq: list[Paper] = []
    for p in cands:
        if p.paper_id in seen:
            continue
        seen.add(p.paper_id)
        p.venue = "arXiv"
        p.venue_track = p.categories[0] if p.categories else ""
        p.track = "ai"
        p.arxiv_id = p.paper_id
        p.proceedings_url = p.url
        p.pdf_url = f"https://arxiv.org/pdf/{p.paper_id}"
        uniq.append(p)
    uniq = uniq[: int(dcfg.get("max_candidates", 120))]
    log.info("[daily %s] %d candidates after prefilter", when, len(uniq))
    if dry_run:
        for p in uniq[:20]:
            print(f"  {p.paper_id}  {p.title[:100]}")
        return None
    if not uniq:
        log.info("[daily %s] no benchmark candidates; nothing to render", when)
        _write_daily_index()
        return None

    interests_text, icfg = load_interests()
    client = SJTUClient()
    scores = score_papers(
        client, uniq, interests_text, model=model, system_prompt=BENCH_SCORE_SYSTEM
    )
    for p in uniq:
        if p.paper_id in scores:
            p.score, p.score_reason = scores[p.paper_id]
    scored = [p for p in uniq if p.score is not None]
    scored.sort(key=lambda p: p.score or 0, reverse=True)

    show = int(dcfg.get("max_shown", 12))
    th_show = float(icfg.get("score_threshold_show", 4))
    to_sum = [p for p in scored if (p.score or 0) >= th_show][: int(dcfg.get("max_summarized", 10))]
    for p in to_sum:
        try:
            summarize_paper(
                client, p, interests_text, model=model,
                system_prompt=BENCH_SUMMARY_SYSTEM, topics=BENCH_TOPICS,
            )
        except Exception as e:  # noqa: BLE001
            log.warning("daily summary failed for %s: %s", p.paper_id, e)

    DAILY_DIR.mkdir(parents=True, exist_ok=True)
    lines = [
        f"# {when.isoformat()} · AI 评测雷达",
        "",
        f"- 候选 **{len(uniq)}** 篇（arXiv {', '.join(arxiv_cfg['categories'])}）· "
        f"打分 **{len(scored)}** · 精摘 **{len(to_sum)}**",
        "",
    ]
    groups = _topic_groups([p for p in scored if p.summary_zh])
    for topic in BENCH_TOPICS:
        items = groups.get(topic, [])
        if not items:
            continue
        lines.append(f"## {BENCH_TOPIC_LABELS_ZH.get(topic, topic)}")
        lines.append("")
        for i, p in enumerate(items[:show], 1):
            lines.extend(card(p, i))
            lines.append("")
    if len(scored) > len(to_sum):
        lines += ["## 其他候选", "", "| 论文 | 来源 | 分数 | 链接 |", "|---|---|---:|---|"]
        for p in scored[len(to_sum):][:30]:
            links = []
            if p.url:
                links.append(f"[页]({p.url})")
            if p.pdf_url:
                links.append(f"[PDF]({p.pdf_url})")
            lines.append(
                f"| {p.title.replace('|', chr(92) + '|')} | {p.venue_track or '-'} | "
                f"{p.score:.0f} | {' · '.join(links) or '-'} |"
            )
        lines.append("")
    out = _write(DAILY_DIR / f"{when.isoformat()}.md", lines)

    _write_daily_index()
    usage_report(client, "benchmarks-daily")
    log.info("[daily %s] rendered %s", when, out)
    return out


# ── status / CLI ─────────────────────────────────────────────────────────────

def status(cfg: dict) -> str:
    rows = ["venue | collected | scored | summarized | updated", "---|---|---|---|---"]
    for v in cfg.get("venues", []):
        m = load_meta(v["id"])
        if not m:
            continue
        rows.append(
            f"{v['label']} | {m.get('papers', 0)} | {m.get('scored', 0)} | "
            f"{m.get('summarized', 0)} | {m.get('updated', '-')}"
        )
    return "\n".join(rows)


def _setup_logging() -> None:
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s %(levelname)s %(name)s: %(message)s",
        datefmt="%H:%M:%S",
    )


def main(argv: list[str] | None = None) -> int:
    cfg = load_config()
    ap = argparse.ArgumentParser(prog="python -m research_news.benchmarks")
    sub = ap.add_subparsers(dest="cmd", required=True)

    p_collect = sub.add_parser("collect", help="crawl a venue's proceedings and prefilter")
    p_collect.add_argument("--venue", required=True)
    p_collect.add_argument("--force", action="store_true")

    p_score = sub.add_parser("score", help="LLM-score collected candidates")
    p_score.add_argument("--venue", required=True)
    p_score.add_argument("--max", type=int, default=None)
    p_score.add_argument("--model", default=None)
    p_score.add_argument("--force", action="store_true")

    p_sum = sub.add_parser("summarize", help="annotate the top papers")
    p_sum.add_argument("--venue", required=True)
    p_sum.add_argument("--max", type=int, default=None)
    p_sum.add_argument("--model", default=None)

    p_run = sub.add_parser("run", help="collect + score + summarize + render one venue")
    p_run.add_argument("--venue", required=True)
    p_run.add_argument("--max-score", type=int, default=None)
    p_run.add_argument("--max-summaries", type=int, default=None)
    p_run.add_argument("--model", default=None)
    p_run.add_argument("--force", action="store_true")

    p_render = sub.add_parser("render", help="render venue pages, index and nav")
    p_render.add_argument("--venue", action="append", default=None,
                          help="repeatable; default = every venue with papers.json")

    p_daily = sub.add_parser("daily", help="daily arXiv benchmark radar")
    p_daily.add_argument("--date", default=None)
    p_daily.add_argument("--model", default=None)
    p_daily.add_argument("--dry-run", action="store_true")

    sub.add_parser("status", help="progress table")

    args = ap.parse_args(argv)
    _setup_logging()

    if args.cmd == "collect":
        collect(venue_cfg(cfg, args.venue), cfg, force=args.force)
    elif args.cmd == "score":
        score_venue(args.venue, cfg, max_n=args.max, model=args.model, force=args.force)
    elif args.cmd == "summarize":
        summarize_venue(args.venue, cfg, max_n=args.max, model=args.model)
    elif args.cmd == "run":
        vcfg = venue_cfg(cfg, args.venue)
        collect(vcfg, cfg, force=args.force)
        score_venue(args.venue, cfg, max_n=args.max_score, model=args.model)
        summarize_venue(args.venue, cfg, max_n=args.max_summaries, model=args.model)
        render_venue(args.venue, cfg)
        render_index(cfg)
        render_nav(cfg)
    elif args.cmd == "render":
        venues = args.venue or [
            v["id"] for v in cfg.get("venues", []) if load_papers(v["id"])
        ]
        for vid in venues:
            render_venue(vid, cfg)
        render_index(cfg)
        render_nav(cfg)
    elif args.cmd == "daily":
        when = date.fromisoformat(args.date) if args.date else None
        daily(when, model=args.model, dry_run=args.dry_run)
    elif args.cmd == "status":
        print(status(cfg))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
